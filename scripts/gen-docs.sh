#!/bin/sh
# Generates docs/reference/*.md from the Go packages' documentation (go doc).
#   scripts/gen-docs.sh
set -eu
cd "$(dirname "$0")/.."
OUT=docs/reference
rm -rf "$OUT"
mkdir -p "$OUT"
MODULE=$(go list -m)
{
  echo "# Package reference"
  echo
  echo "Generated by \`scripts/gen-docs.sh\` from the code's doc comments. Do not edit by hand."
  echo
  echo "| Package | Summary |"
  echo "|---|---|"
} > "$OUT/README.md"
for pkg in $(go list ./internal/... ./cmd/...); do
  rel=${pkg#"$MODULE"/}
  name=$(echo "$rel" | tr '/' '-')
  synopsis=$(go list -f '{{.Doc}}' "$pkg")
  echo "| [\`$rel\`]($name.md) | $synopsis |" >> "$OUT/README.md"
  {
    echo "# \`$rel\`"
    echo
    echo '```'
    go doc -all "$pkg" 2>/dev/null || go doc "$pkg"
    echo '```'
  } > "$OUT/$name.md"
done
echo "Wrote $(ls "$OUT" | wc -l | tr -d ' ') files to $OUT"
